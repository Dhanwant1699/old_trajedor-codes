"""
AI Trade & Signal Ledger for AI Trading Council.
Maintains a 100% verified, persistent audit log of ONLY trades and signals generated by our AI automation:
1. EXECUTED TRADES: Orders submitted to MT5 by AI with ticket, entry, SL/TP, realized PnL, and close reasons.
2. MISSED ENTRIES: High-conviction AI signals (quorum >= 75%) that were vetoed/blocked by CRO risk rules
   (e.g., high spread, news blackout, drawdown limit) or rejected by broker execution.
"""

import json
import os
from datetime import datetime, timezone, timedelta
from typing import Dict, Any, List, Optional
from config import CONFIG


LEDGER_DIR = os.path.join(os.path.dirname(__file__), "..", "data")
LEDGER_FILE = os.path.join(LEDGER_DIR, "ai_trade_history.json")


class AITradeLedger:
    @staticmethod
    def _ensure_ledger_file():
        os.makedirs(LEDGER_DIR, exist_ok=True)
        if not os.path.exists(LEDGER_FILE):
            initial_data = {
                "version": "1.0",
                "ai_trades": [],
                "missed_entries": []
            }
            with open(LEDGER_FILE, "w", encoding="utf-8") as f:
                json.dump(initial_data, f, indent=2)

    @classmethod
    def load_ledger(cls) -> Dict[str, Any]:
        cls._ensure_ledger_file()
        try:
            with open(LEDGER_FILE, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            return {"version": "1.0", "ai_trades": [], "missed_entries": []}

    @classmethod
    def save_ledger(cls, data: Dict[str, Any]):
        cls._ensure_ledger_file()
        try:
            with open(LEDGER_FILE, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=2)
        except Exception as e:
            print(f"[AITradeLedger] Error saving ledger: {e}")

    @classmethod
    def record_executed_trade(
        cls,
        ticket: int,
        symbol: str,
        action: str,
        volume: float,
        price: float,
        sl: float,
        tp: float,
        consensus_score: int = 85,
        comment: str = "Chanakya_Trade"
    ):
        """Logs a newly executed AI trade."""
        data = cls.load_ledger()
        trades = data.get("ai_trades", [])

        # Check if ticket already exists
        for t in trades:
            if t.get("ticket") == ticket:
                return

        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        entry = {
            "ticket": ticket,
            "time": now_str,
            "symbol": symbol,
            "action": action.upper(),
            "volume": round(float(volume), 2),
            "entry_price": round(float(price), 2),
            "sl": round(float(sl), 2) if sl else 0.0,
            "tp": round(float(tp), 2) if tp else 0.0,
            "consensus_score": consensus_score,
            "comment": comment,
            "status": "OPEN",
            "realized_pnl": 0.0,
            "exit_price": None,
            "exit_time": None,
            "exit_reason": None,
            "result": "OPEN"
        }
        trades.insert(0, entry)
        data["ai_trades"] = trades
        cls.save_ledger(data)
        print(f"[AITradeLedger] 📝 Logged AI Executed Trade: Ticket #{ticket} {action} {volume} lots @ {price}")

    @classmethod
    def record_missed_entry(
        cls,
        symbol: str,
        action: str,
        target_price: float,
        sl: float,
        tp: float,
        consensus_score: int,
        veto_source: str,
        reason: str
    ):
        """Logs a missed/vetoed signal where AI consensus reached >= 75% but trade was not placed."""
        data = cls.load_ledger()
        missed = data.get("missed_entries", [])

        now = datetime.now()
        now_str = now.strftime("%Y-%m-%d %H:%M:%S")
        miss_id = f"MISS_{now.strftime('%Y%m%d_%H%M%S')}_{symbol}"

        # Prevent duplicate logs within 5 minutes for the same symbol/action
        for m in missed[:5]:
            if m.get("symbol") == symbol and m.get("action") == action and m.get("reason") == reason:
                # Check if logged recently
                try:
                    last_time = datetime.strptime(m.get("time"), "%Y-%m-%d %H:%M:%S")
                    if (now - last_time).total_seconds() < 300:
                        return
                except Exception:
                    pass

        entry = {
            "id": miss_id,
            "time": now_str,
            "symbol": symbol,
            "action": action.upper(),
            "target_price": round(float(target_price), 2),
            "sl": round(float(sl), 2) if sl else 0.0,
            "tp": round(float(tp), 2) if tp else 0.0,
            "consensus_score": consensus_score,
            "veto_source": veto_source,
            "reason": reason,
            "result": "MISSED_ENTRY"
        }
        missed.insert(0, entry)
        # Keep maximum 100 missed entries
        data["missed_entries"] = missed[:100]
        cls.save_ledger(data)
        print(f"[AITradeLedger] ⚠️ Logged Missed AI Entry: {symbol} {action} | Reason: {reason}")

    @classmethod
    def sync_with_mt5_ai_deals(cls, days: int = 30) -> Dict[str, Any]:
        """
        Syncs with MetaTrader 5 history across all connected terminals,
        grouping deals by position_id so that each trade lifecycle (Entry -> Partial Closes -> Final Exit)
        is accurately reconstructed as 1 consolidated position entry with the correct initial direction,
        entry price, total closed volume, and true net realized P&L.
        Strictly filters ONLY deals placed by our AI (matching Magic Numbers 777888 / 777999 / CONFIG.MAGIC_NUMBER or AI comments).
        Manual trades are 100% excluded.
        """
        from collections import defaultdict
        # Load all configured accounts from admin_config.json
        admin_cfg_path = os.path.join(LEDGER_DIR, "admin_config.json")
        terminals = []
        ai_magic_numbers = {CONFIG.MAGIC_NUMBER, CONFIG.MAGIC_NUMBER + 111, 777888, 777999, 778101, 778110, 778221}
        if os.path.exists(admin_cfg_path):
            try:
                with open(admin_cfg_path, "r", encoding="utf-8") as f:
                    admin_cfg = json.load(f)
                for k, a in admin_cfg.get("accounts", {}).items():
                    if a.get("terminal_path"):
                        terminals.append({
                            "id": k,
                            "name": a.get("name", k),
                            "path": a.get("terminal_path"),
                            "currency": a.get("currency", "USD")
                        })
                    if a.get("magic_number"):
                        ai_magic_numbers.add(int(a["magic_number"]))
            except Exception:
                pass

        if not terminals:
            terminals = [
                {"id": "acc_1", "name": "Account #1 (Master EUR)", "path": r"C:\Program Files\MetaTrader 5\terminal64.exe", "currency": "EUR"},
                {"id": "acc_2", "name": "Account #2 (GTC Live Micro USD)", "path": r"C:\Program Files\MetaTrader 5 - 1\terminal64.exe", "currency": "USD"},
                {"id": "acc_3", "name": "Account #3 (VantageMarkets-Demo)", "path": r"C:\Program Files\MetaTrader 5 - 2\terminal64.exe", "currency": "USD"},
                {"id": "acc_4", "name": "Account #4 (GTCGlobalSA-Server 2)", "path": r"C:\Program Files\MetaTrader 5 - 3\terminal64.exe", "currency": "USD"}
            ]

        data = cls.load_ledger()
        local_trades = {t.get("ticket"): t for t in data.get("ai_trades", []) if t.get("ticket")}
        missed_entries = data.get("missed_entries", [])

        try:
            import MetaTrader5 as mt5
            from_date = datetime.now() - timedelta(days=days)
            to_date = datetime.now() + timedelta(days=1)

            for term in terminals:
                acc_id = term["id"]
                acc_name = term["name"]
                acc_curr = term["currency"]
                try:
                    if mt5.initialize(path=term["path"]):
                        deals = mt5.history_deals_get(from_date, to_date)
                        mt5.shutdown()

                        if deals:
                            positions_map = defaultdict(list)
                            for d in deals:
                                is_ai_deal = (d.magic in ai_magic_numbers) or (d.comment and (str(d.comment).upper().startswith("AI_") or "CHANAKYA" in str(d.comment).upper()))
                                if is_ai_deal:
                                    pos_id = d.position_id or d.order or d.ticket
                                    positions_map[pos_id].append(d)

                            for pos_id, p_deals in positions_map.items():
                                in_deals = [d for d in p_deals if d.entry == 0]
                                in_deal = in_deals[0] if in_deals else p_deals[0]
                                out_deals = [d for d in p_deals if d.entry == 1]

                                initial_action = "BUY" if in_deal.type == 0 else "SELL"
                                initial_price = round(float(in_deal.price), 2)
                                initial_vol = round(float(in_deal.volume), 2)
                                open_time = datetime.fromtimestamp(in_deal.time).strftime("%Y-%m-%d %H:%M:%S")

                                total_pnl = round(float(sum(d.profit for d in out_deals)), 2)
                                total_closed_vol = round(float(sum(d.volume for d in out_deals)), 2)

                                last_out = out_deals[-1] if out_deals else None
                                exit_price = round(float(last_out.price), 2) if last_out else None
                                exit_time = datetime.fromtimestamp(last_out.time).strftime("%Y-%m-%d %H:%M:%S") if last_out else None
                                exit_reason = str(last_out.comment) if last_out and last_out.comment else "MT5 Execution Exit"

                                is_closed = (total_closed_vol >= initial_vol and initial_vol > 0)
                                status = "CLOSED" if is_closed else "OPEN"
                                if status == "CLOSED":
                                    result_type = "WIN" if total_pnl > 0 else "LOSS" if total_pnl < 0 else "BREAKEVEN"
                                else:
                                    result_type = "OPEN"

                                local_trades[pos_id] = {
                                    "ticket": pos_id,
                                    "time": open_time,
                                    "symbol": in_deal.symbol,
                                    "action": initial_action,
                                    "volume": initial_vol,
                                    "entry_price": initial_price,
                                    "sl": 0.0,
                                    "tp": 0.0,
                                    "consensus_score": 85,
                                    "comment": in_deal.comment or "Chanakya_Trade",
                                    "status": status,
                                    "realized_pnl": total_pnl,
                                    "exit_price": exit_price,
                                    "exit_time": exit_time,
                                    "exit_reason": exit_reason,
                                    "result": result_type,
                                    "account_id": acc_id,
                                    "account_name": acc_name,
                                    "currency": acc_curr
                                }
                except Exception as ex_term:
                    print(f"[AITradeLedger] Warning scanning terminal {acc_id}: {ex_term}")

        except Exception as e:
            print(f"[AITradeLedger] Error querying MT5 history: {e}")

        # Combine all AI trades & sort by time descending
        all_ai_trades = list(local_trades.values())
        all_ai_trades.sort(key=lambda x: x.get("time", ""), reverse=True)

        # Update saved ledger
        data["ai_trades"] = all_ai_trades
        cls.save_ledger(data)

        # Calculate AI Performance Metrics
        closed_trades = [t for t in all_ai_trades if t.get("status") == "CLOSED" or t.get("result") in ["WIN", "LOSS", "BREAKEVEN"]]
        wins = [t for t in closed_trades if t.get("result") == "WIN"]
        losses = [t for t in closed_trades if t.get("result") == "LOSS"]
        net_pnl = sum([t.get("realized_pnl", 0.0) for t in closed_trades])

        total_closed = len(closed_trades)
        win_rate = round((len(wins) / total_closed * 100), 1) if total_closed > 0 else 0.0

        # Build unified ledger item list (Executed Trades + Missed Entries)
        unified_ledger = []
        for t in all_ai_trades:
            pnl = t.get("realized_pnl", 0.0)
            curr_sym = "€" if t.get("currency") == "EUR" else "$"
            pnl_str = f"+{curr_sym}{pnl:.2f}" if pnl >= 0 else f"-{curr_sym}{abs(pnl):.2f}"
            unified_ledger.append({
                "type_category": "EXECUTED",
                "ticket": t.get("ticket"),
                "time": t.get("time"),
                "symbol": t.get("symbol"),
                "type": t.get("action"),
                "volume": t.get("volume"),
                "price": t.get("entry_price"),
                "sl": t.get("sl"),
                "tp": t.get("tp"),
                "profit": pnl,
                "profit_str": pnl_str,
                "account_id": t.get("account_id", "acc_1"),
                "account_name": t.get("account_name", "Account #1 (Master EUR)"),
                "currency": t.get("currency", "EUR"),
                "comment": t.get("comment", ""),
                "exit_reason": t.get("exit_reason") or t.get("comment") or "Active / Closed",
                "result": t.get("result", "OPEN"),
                "consensus": t.get("consensus_score", 85)
            })

        for m in missed_entries:
            unified_ledger.append({
                "type_category": "MISSED",
                "ticket": m.get("id"),
                "time": m.get("time"),
                "symbol": m.get("symbol"),
                "type": m.get("action"),
                "volume": 0.0,
                "price": m.get("target_price"),
                "sl": m.get("sl"),
                "tp": m.get("tp"),
                "profit": 0.0,
                "profit_str": "€0.00 (Vetoed)",
                "account_id": "ALL",
                "account_name": "All Accounts (Signal Veto)",
                "currency": "EUR",
                "comment": f"[{m.get('veto_source')}] {m.get('reason')}",
                "exit_reason": m.get("reason"),
                "result": "MISSED_ENTRY",
                "consensus": m.get("consensus_score", 80)
            })

        unified_ledger.sort(key=lambda x: x.get("time", ""), reverse=True)

        return {
            "total_ai_trades": total_closed,
            "wins": len(wins),
            "losses": len(losses),
            "win_rate": win_rate,
            "net_pnl": round(net_pnl, 2),
            "missed_entries_count": len(missed_entries),
            "trades": unified_ledger
        }

